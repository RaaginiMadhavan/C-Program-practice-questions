//and,or,not
#include<stdio.h>
int main(){
	printf("And:%d",5>7&&7>33);//LOGICAL AND o/p:0
	printf("\nOr:%d",55>5|56>49);//LOGICAL OR o/p:1
	printf("\nNot:%d",!0);//LOGICAL NOT o/p:1
	printf("\nAnd Bit:%d",15&9);//BITWISE AND o/p:
	printf("\nOr Bit:%d",33|11);//BITWISE OR o/p:
	printf("\nNot Bit:%d",~1);//BITWISE NOT o/p:-2
	printf("\nXOR:%d",13^11);//XOR
	}
